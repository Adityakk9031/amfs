"""The evidence functions, rendered from ``amfs_core.evidence``.

Migrations 008 and 009 wrote the outcome arithmetic twice: once in Python
(``amfs_core.evidence``) and once by hand in PL/pgSQL, with the constants —
decay, prior strength, discredit threshold, first-strike wins, the severity
and multiplier tables, the validator cap — copied into the SQL as literals.
Either side could drift and nothing would say so until the integration tests
disagreed with each other.

This module is the one place the SQL comes from. :func:`render_evidence_sql`
reads the constants and tables off the Python model and renders the scalar
functions and ``amfs_apply_outcome_step`` with them; migration 012 is that
rendering, committed, and a unit test asserts the committed file equals the
rendering. Change a constant in Python without regenerating the migration and
the test fails; change the SQL by hand and it fails the same way.

The arithmetic stays in the database rather than moving to the app layer
because the trigger is what makes an outcome's effect atomic with its row,
across every writer (SDK, HTTP server, MCP) and every language — the
alternative is a second write path per client that can race the first.
"""

from __future__ import annotations

from amfs_core import evidence as ev
from amfs_core.models import OUTCOME_MULTIPLIERS

MIGRATION_NAME = "012_evidence_from_model.sql"


def _num(value: float) -> str:
    """A NUMERIC literal: the shortest repr that round-trips, always with a
    decimal point so the SQL reads as the numeric it is."""
    return repr(float(value))


def _sql_list(names: list[str]) -> str:
    return ",\n                 ".join(f"'{n}'" for n in names)


def _case(table: dict[str, float], default: float) -> str:
    lines = [f"        WHEN '{name}' THEN {_num(value)}" for name, value in table.items()]
    lines.append(f"        ELSE {_num(default)}")
    return "\n".join(lines)


def render_evidence_sql() -> str:
    """The text of migration 012: the evidence functions from the model."""
    success_types = sorted(ev.SUCCESS_TYPES)
    known_types = list(ev.SEVERITY.keys())
    multipliers = {
        (k.value if hasattr(k, "value") else str(k)): float(v)
        for k, v in OUTCOME_MULTIPLIERS.items()
    }
    return f"""-- Migration 012: the evidence functions, rendered from amfs_core.evidence
--
-- GENERATED by amfs_postgres.evidence_sql.render_evidence_sql(). Do not edit:
-- change the constant or table in amfs_core.evidence and regenerate with
--
--     python -m amfs_postgres.evidence_sql \\
--         > packages/adapters/postgres/src/amfs_postgres/migrations/{MIGRATION_NAME}
--
-- tests/unit/test_evidence_sql_from_model.py fails when this file and the
-- rendering differ, so a constant changed on one side cannot ship alone.
--
-- Replaces the hand-written bodies from 008 and 009 with the same arithmetic
-- read off the Python model: SUCCESS_TYPES, SEVERITY, OUTCOME_MULTIPLIERS,
-- EVIDENCE_DECAY = {_num(ev.EVIDENCE_DECAY)}, PRIOR_STRENGTH = {_num(ev.PRIOR_STRENGTH)},
-- DISCREDIT_THRESHOLD = {_num(ev.DISCREDIT_THRESHOLD)},
-- FIRST_STRIKE_MIN_WINS = {ev.FIRST_STRIKE_MIN_WINS}, MAX_VALIDATORS = {ev.MAX_VALIDATORS}.
-- The row-copy shape (007), the credited
-- claim rule (versions) and the trigger (009) are unchanged.

CREATE OR REPLACE FUNCTION amfs_outcome_is_success(t TEXT) RETURNS BOOLEAN AS $$
    SELECT t IN ({_sql_list(success_types)});
$$ LANGUAGE sql IMMUTABLE;

CREATE OR REPLACE FUNCTION amfs_outcome_is_known(t TEXT) RETURNS BOOLEAN AS $$
    SELECT t IN ({_sql_list(known_types)});
$$ LANGUAGE sql IMMUTABLE;

CREATE OR REPLACE FUNCTION amfs_outcome_severity(t TEXT) RETURNS NUMERIC AS $$
    SELECT CASE t
{_case(dict(ev.SEVERITY), 1.0)}
    END;
$$ LANGUAGE sql IMMUTABLE;

-- The 006 multipliers, kept for AMFS_OUTCOME_MODEL=multiplicative.
CREATE OR REPLACE FUNCTION amfs_outcome_multiplier(t TEXT) RETURNS NUMERIC AS $$
    SELECT CASE t
{_case(multipliers, 1.0)}
    END;
$$ LANGUAGE sql IMMUTABLE;

CREATE OR REPLACE FUNCTION amfs_apply_outcome_step(
    p_namespace TEXT,
    p_account UUID,
    p_keys TEXT[],
    p_outcome_type TEXT,
    p_causal_confidence NUMERIC,
    p_model TEXT,
    p_versions JSONB,
    p_agent TEXT
) RETURNS INTEGER AS $$
DECLARE
    keys TEXT[];
    entry_key TEXT;
    ep TEXT;
    k TEXT;
    cur RECORD;
    read_version INTEGER;
    read_value JSONB;
    n_keys INTEGER;
    is_ok BOOLEAN;
    target NUMERIC;
    w NUMERIC;
    prior NUMERIC;
    e_s NUMERIC;
    e_f NUMERIC;
    new_conf NUMERIC;
    disc TIMESTAMPTZ;
    surprise NUMERIC;
    vals JSONB;
    touched INTEGER := 0;
    -- amfs_core.evidence, rendered:
    c_decay CONSTANT NUMERIC := {_num(ev.EVIDENCE_DECAY)};
    c_prior_strength CONSTANT NUMERIC := {_num(ev.PRIOR_STRENGTH)};
    c_discredit CONSTANT NUMERIC := {_num(ev.DISCREDIT_THRESHOLD)};
    c_first_strike_wins CONSTANT INTEGER := {ev.FIRST_STRIKE_MIN_WINS};
    c_max_validators CONSTANT INTEGER := {ev.MAX_VALIDATORS};
BEGIN
    -- Distinct, well-formed specs only; a key cited twice is one citation.
    SELECT COALESCE(array_agg(DISTINCT x), '{{}}') INTO keys
    FROM unnest(COALESCE(p_keys, '{{}}')) AS x
    WHERE position('/' in x) > 0;
    n_keys := cardinality(keys);
    IF n_keys = 0 THEN
        RETURN 0;
    END IF;

    -- An outcome type neither side of the model knows is not evidence of
    -- anything (the multipliers treated it as x1.0; this treats it as no step).
    IF NOT amfs_outcome_is_known(p_outcome_type) THEN
        RETURN 0;
    END IF;
    is_ok := amfs_outcome_is_success(p_outcome_type);
    target := CASE WHEN is_ok THEN 1.0 ELSE 0.0 END;

    FOREACH entry_key IN ARRAY keys
    LOOP
        -- Last-slash split, matching Python's rsplit("/", 1).
        k := substring(entry_key from '([^/]+)$');
        ep := left(entry_key, length(entry_key) - length(k) - 1);

        SELECT * INTO cur FROM amfs_memory_entries
        WHERE namespace = p_namespace
          AND entity_path = ep
          AND key = k
          AND superseded_at IS NULL
          AND account_id IS NOT DISTINCT FROM p_account
        ORDER BY version DESC LIMIT 1;

        IF NOT FOUND THEN
            CONTINUE;
        END IF;

        -- Credit the claim that was read. If the key has been rewritten since
        -- and now says something else, this outcome is about the old claim.
        read_version := NULLIF(COALESCE(p_versions, '{{}}'::jsonb)->>entry_key, '')::INTEGER;
        IF read_version IS NOT NULL AND read_version <> cur.version THEN
            SELECT value INTO read_value FROM amfs_memory_entries
            WHERE namespace = p_namespace
              AND entity_path = ep
              AND key = k
              AND version = read_version
              AND account_id IS NOT DISTINCT FROM p_account
            LIMIT 1;
            IF FOUND AND read_value IS DISTINCT FROM cur.value THEN
                CONTINUE;
            END IF;
        END IF;

        prior := LEAST(1.0, GREATEST(0.0, COALESCE(cur.prior_confidence, cur.confidence)));

        IF p_model = 'multiplicative' THEN
            new_conf := LEAST(1.0, GREATEST(0.0,
                cur.confidence * amfs_outcome_multiplier(p_outcome_type) * p_causal_confidence));
            e_s := COALESCE(cur.evidence_success, 0) + CASE WHEN is_ok THEN 1 ELSE 0 END;
            e_f := COALESCE(cur.evidence_failure, 0) + CASE WHEN is_ok THEN 0 ELSE 1 END;
        ELSE
            -- First strike: the first failure of an entry with a clean record
            -- of at least c_first_strike_wins successes is weighed without the
            -- surprise term (amfs_core.evidence.first_strike). One slip on a
            -- validated rule leaves it contested; the second still discredits it.
            surprise := 1.0 + abs(target - LEAST(1.0, GREATEST(0.0, cur.confidence)));
            IF NOT is_ok AND COALESCE(cur.failure_count, 0) = 0
               AND COALESCE(cur.success_count, 0) >= c_first_strike_wins THEN
                surprise := 1.0;
            END IF;
            w := amfs_outcome_severity(p_outcome_type)
                 * GREATEST(0.0, p_causal_confidence)
                 / n_keys
                 * surprise;
            e_s := COALESCE(cur.evidence_success, 0) * c_decay + CASE WHEN is_ok THEN w ELSE 0 END;
            e_f := COALESCE(cur.evidence_failure, 0) * c_decay + CASE WHEN is_ok THEN 0 ELSE w END;
            new_conf := LEAST(1.0, GREATEST(0.0,
                (c_prior_strength * prior + e_s) / (c_prior_strength + e_s + e_f)));
        END IF;

        IF new_conf < c_discredit AND NOT is_ok THEN
            disc := COALESCE(cur.discredited_at, NOW());
        ELSIF new_conf >= c_discredit THEN
            disc := NULL;
        ELSE
            disc := cur.discredited_at;
        END IF;

        -- Validators: distinct agents whose successes credited this claim,
        -- most recent last, capped (amfs_core.evidence.validators_after).
        vals := COALESCE(cur.validators, '[]'::jsonb);
        IF is_ok AND COALESCE(p_agent, '') <> '' THEN
            vals := vals - p_agent;
            vals := vals || to_jsonb(ARRAY[p_agent]);
            IF jsonb_array_length(vals) > c_max_validators THEN
                SELECT COALESCE(jsonb_agg(v), '[]'::jsonb) INTO vals
                FROM (
                    SELECT v FROM jsonb_array_elements(vals) WITH ORDINALITY AS t(v, ord)
                    ORDER BY ord OFFSET jsonb_array_length(vals) - c_max_validators
                ) s;
            END IF;
        END IF;

        UPDATE amfs_memory_entries
        SET superseded_at = NOW()
        WHERE id = cur.id;

        -- Copy the row (see 007); override only what this version changes.
        INSERT INTO amfs_memory_entries
        SELECT * FROM jsonb_populate_record(
            NULL::amfs_memory_entries,
            to_jsonb(cur) || jsonb_build_object(
                'id', gen_random_uuid(),
                'version', cur.version + 1,
                'confidence', new_conf,
                'outcome_count', cur.outcome_count + 1,
                'success_count', COALESCE(cur.success_count, 0) + CASE WHEN is_ok THEN 1 ELSE 0 END,
                'failure_count', COALESCE(cur.failure_count, 0) + CASE WHEN is_ok THEN 0 ELSE 1 END,
                'evidence_success', e_s,
                'evidence_failure', e_f,
                'prior_confidence', prior,
                'last_outcome', p_outcome_type,
                'last_outcome_at', NOW(),
                'discredited_at', disc,
                'validators', vals,
                'superseded_at', NULL
            )
        );
        touched := touched + 1;
    END LOOP;
    RETURN touched;
END;
$$ LANGUAGE plpgsql;
"""


if __name__ == "__main__":  # pragma: no cover - regeneration entry point
    import sys

    sys.stdout.write(render_evidence_sql())
